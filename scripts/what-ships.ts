#!/usr/bin/env bun
/**
 * Generate `docs/what-ships.md`, the page that lists what the framework already
 * does, from the same list the `AGENTS.md` index is built from.
 *
 *   bun run scripts/what-ships.ts            # write
 *   bun run scripts/what-ships.ts --check    # fail if the page is stale
 *
 * One list, two readers. A coding agent reads it in `AGENTS.md`, marked against
 * the app it is in; a person reads it here, grouped by area and linked. Written
 * by hand, the page would be a second copy of the list, and the two would start
 * disagreeing on the first capability added to one of them.
 *
 * Where each capability comes from is worked out here rather than stored:
 * "built in" when it has no package, "included with `zerotal`" when the package is
 * one the bundle depends on, and "add `@zerotal/x`" otherwise. The bundle's own
 * manifest decides the middle one, so the page follows it.
 */
import { join } from "node:path";
import { CAPABILITIES, CAPABILITY_AREAS } from "../packages/arch/src/install/guidelines.ts";
import type { Capability } from "../packages/arch/src/install/guidelines.ts";

const ROOT = join(import.meta.dir, "..");
const PAGE = join(ROOT, "docs", "what-ships.md");

const check = process.argv.includes("--check");

const bundle = (await Bun.file(join(ROOT, "packages", "zerotal", "package.json")).json()) as {
  dependencies?: Record<string, string>;
};
const bundled = new Set(Object.keys(bundle.dependencies ?? {}));

function source(capability: Capability): string {
  if (capability.pkg === undefined) return "Built in.";
  if (bundled.has(capability.pkg)) return "Included with `zerotal`.";
  return `Add \`${capability.pkg}\`.`;
}

function line(capability: Capability): string {
  return `- **[${capability.need}](/docs/${capability.doc})** — ${capability.provides}. ${source(capability)}`;
}

export function renderPage(): string {
  const sections = CAPABILITY_AREAS.map((area) => {
    const entries = CAPABILITIES.filter((capability) => capability.area === area);
    return entries.length === 0 ? "" : [`## ${area}`, "", ...entries.map(line)].join("\n");
  }).filter(Boolean);

  return [
    "---",
    "title: What Ships",
    "description: Everything the framework already does, by area — what provides it, where it comes from, and the page that covers it. Check here before building one.",
    "---",
    "",
    "<!-- Generated by `bun run docs:what-ships` from the capability list in",
    "     packages/arch/src/install/guidelines.ts. Edit that list, not this page. -->",
    "",
    "# What Ships",
    "",
    "Before you build something an app commonly needs, check whether the framework",
    "already does it. Each line below links to the page that covers it and says where",
    "it comes from:",
    "",
    "- **Built in** — part of the kernel every app has.",
    "- **Included with `zerotal`** — one of the packages the `zerotal` bundle installs.",
    "  Every starter depends on it.",
    "- **Add `@zerotal/…`** — a separate package. Install it with `bun add`.",
    "",
    "A coding agent working in your app gets the same list in `AGENTS.md`, marked",
    "against what the app has installed. See [Agent Surface](/docs/arch).",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

const expected = renderPage();
const current = (await Bun.file(PAGE).exists()) ? await Bun.file(PAGE).text() : undefined;

if (check) {
  if (current !== expected) {
    console.error(
      "docs/what-ships.md is stale. Run `bun run docs:what-ships` and commit the result.",
    );
    process.exit(1);
  }
  console.log("docs:what-ships — docs/what-ships.md is current.");
} else if (current !== expected) {
  await Bun.write(PAGE, expected);
  console.log("wrote docs/what-ships.md");
}
